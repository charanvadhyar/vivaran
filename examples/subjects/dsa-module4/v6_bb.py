def short(notes):
    out = []
    for n in notes:
        num, rest = n.split(" ", 1); lab, what = rest.split(":", 1) if ":" in rest else (rest, "")
        what = what.strip()
        out.append(f"{num} {lab.strip()} {'✓' if what == 'live' else ('answer' if 'answer' in what else '✗')}")
    return " · ".join(out)
